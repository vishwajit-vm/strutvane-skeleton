/**
 * The skeleton as a real app: render it, install the real @strutvane/framework, then type-check,
 * migrate, seed, run the app's own tests, boot the server and call `/up`.
 *
 * Where the framework comes from, in order:
 * 1. `STRUT_FRAMEWORK_TARBALL`: a tarball path (CI can point this at a downloaded release);
 * 2. `npm pack` of the sibling checkout `../framework` (the hub's local layout), when its `dist/`
 *    is built and newer than its `src/`.
 *
 * Until @strutvane/framework 0.2.0-next.0 is on npm, CI has neither, so this suite is skipped
 * there with the reason in its title. Nothing here is committed: the app lives in the git-ignored
 * `.work/it-app` (not the OS temp folder, which the CLI refuses as a project root), and its
 * `node_modules` is reused between runs while the tarball and package.json stay the same.
 *
 * `STRUT_UPDATE_GENERATED=1` copies the `.strutvane/` files that `migrate` regenerated back into
 * `template/.strutvane/` instead of failing when they differ.
 */
import { type SpawnSyncReturns, spawn, spawnSync } from 'node:child_process'
import { createHash, randomBytes } from 'node:crypto'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { createServer } from 'node:net'
import { dirname, join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { resolveAnswers } from '../src/manifest.ts'
import { renderSkeleton } from '../src/render.ts'
import { manifest, ROOT, TEMPLATE } from './helpers.ts'

const WORK = join(ROOT, '.work')
const APP = join(WORK, 'it-app')
const FRAMEWORK_DIR = join(ROOT, '..', 'framework')
/** The generated files the template commits (regenerated by `migrate`, compared below). */
const GENERATED = manifest.files
  .map((file) => file.path)
  .filter((path) => path.startsWith('.strutvane/'))

/** The newest modification time of any file under a folder. */
function newest(folder: string): number {
  let latest = 0
  for (const entry of readdirSync(folder, { recursive: true, withFileTypes: true }))
    if (entry.isFile())
      latest = Math.max(latest, statSync(join(entry.parentPath, entry.name)).mtimeMs)
  return latest
}

/** Run a program to completion in an app folder; never through a shell. */
function run(
  args: readonly string[],
  timeoutMs = 300_000,
  cwd: string = APP,
  extraEnv: NodeJS.ProcessEnv = {},
): SpawnSyncReturns<string> {
  return spawnSync(process.execPath, args, {
    cwd,
    env: { ...childEnv(), ...extraEnv },
    encoding: 'utf8',
    timeout: timeoutMs,
    windowsHide: true,
  })
}

/** The environment for the app's processes: no test-runner variables, no colours. */
function childEnv(): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {}
  for (const [key, value] of Object.entries(process.env))
    if (!/^(VITEST|NODE_ENV$|APP_|DB_|LOG_|TEST)/.test(key)) env[key] = value
  return { ...env, NO_COLOR: '1', FORCE_COLOR: '0' }
}

/** Fail with the command's whole output, so a red run says why. */
function expectOk(result: SpawnSyncReturns<string>, what: string): string {
  const output = `${result.stdout ?? ''}${result.stderr ?? ''}`
  if (result.error !== undefined) throw new Error(`${what} could not run: ${result.error.message}`)
  expect(result.status, `${what} failed:\n${output}`).toBe(0)
  return output
}

/** Find (or make) the framework tarball, or say why there is none. */
function frameworkTarball(): { readonly path: string } | { readonly reason: string } {
  const given = process.env['STRUT_FRAMEWORK_TARBALL']
  if (given !== undefined && given !== '')
    return existsSync(given)
      ? { path: given }
      : { reason: `STRUT_FRAMEWORK_TARBALL=${given} does not exist` }
  const manifestFile = join(FRAMEWORK_DIR, 'package.json')
  if (!existsSync(manifestFile))
    return {
      reason:
        'no framework tarball: @strutvane/framework 0.2.0-next.0 is not on npm yet and ../framework is not checked out',
    }
  const pkg = JSON.parse(readFileSync(manifestFile, 'utf8')) as { name?: string; version?: string }
  if (pkg.name !== '@strutvane/framework' || !String(pkg.version).startsWith('0.2.'))
    return {
      reason: `../framework is ${String(pkg.name)}@${String(pkg.version)}, not @strutvane/framework 0.2.x`,
    }
  const bin = join(FRAMEWORK_DIR, 'dist', 'console', 'bin.mjs')
  if (!existsSync(bin) || statSync(bin).mtimeMs < newest(join(FRAMEWORK_DIR, 'src')))
    return {
      reason:
        '../framework/dist is missing or older than its src: run npx tsdown in packages/framework',
    }
  const tarball = join(WORK, 'pack', `strutvane-framework-${pkg.version}.tgz`)
  if (!existsSync(tarball) || statSync(tarball).mtimeMs < statSync(bin).mtimeMs) {
    mkdirSync(dirname(tarball), { recursive: true })
    const npm = npmCli()
    const packed = spawnSync(
      process.execPath,
      [npm, 'pack', '--pack-destination', dirname(tarball)],
      {
        cwd: FRAMEWORK_DIR,
        encoding: 'utf8',
        timeout: 120_000,
        windowsHide: true,
      },
    )
    if (packed.status !== 0) return { reason: `npm pack of ../framework failed: ${packed.stderr}` }
  }
  return { path: tarball }
}

/** npm's JS entry next to this node (never npm.cmd: no cmd.exe parsing our arguments). */
function npmCli(): string {
  const home = dirname(process.execPath)
  const candidates = [
    join(home, 'node_modules', 'npm', 'bin', 'npm-cli.js'),
    join(home, '..', 'lib', 'node_modules', 'npm', 'bin', 'npm-cli.js'),
  ]
  const found = candidates.find((candidate) => existsSync(candidate))
  if (found === undefined) throw new Error(`npm-cli.js was not found next to ${process.execPath}`)
  return found
}

/** A free TCP port on 127.0.0.1. */
function freePort(): Promise<number> {
  return new Promise((resolvePort, reject) => {
    const server = createServer()
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      const address = server.address()
      const port = typeof address === 'object' && address !== null ? address.port : 0
      server.close(() => resolvePort(port))
    })
  })
}

/** Poll a URL until it answers 200, or give up. */
async function waitFor(url: string, timeoutMs: number): Promise<void> {
  const deadline = Date.now() + timeoutMs
  let last = 'no answer'
  while (Date.now() < deadline) {
    try {
      const response = await fetch(url)
      if (response.status === 200) return
      last = `HTTP ${response.status}`
    } catch (error) {
      last = error instanceof Error ? error.message : String(error)
    }
    await new Promise((wait) => setTimeout(wait, 250))
  }
  throw new Error(`${url} did not answer 200 within ${timeoutMs} ms (${last})`)
}

/**
 * Render a variant into `dir` and install the given package tarballs, keeping a matching
 * node_modules between runs (same tarballs, same package.json).
 */
function renderApp(
  dir: string,
  given: Readonly<Record<string, string | boolean>>,
  tarballs: readonly string[],
): void {
  const answers = resolveAnswers(manifest, given)
  const files = renderSkeleton({ root: ROOT, manifest, answers })
  const pkg = files.find((file) => file.path === 'package.json')?.content ?? ''
  const hash = createHash('sha256').update(pkg)
  for (const tarball of tarballs) hash.update(readFileSync(tarball))
  const stamp = hash.digest('hex')
  const stampFile = join(dir, 'node_modules', '.skeleton-stamp')
  const reuse = existsSync(stampFile) && readFileSync(stampFile, 'utf8') === stamp
  if (existsSync(dir))
    for (const entry of readdirSync(dir))
      if (!(reuse && entry === 'node_modules'))
        rmSync(join(dir, entry), { recursive: true, force: true })
  for (const file of files) {
    const path = join(dir, ...file.path.split('/'))
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, file.content)
  }
  if (!reuse) {
    expectOk(
      run([npmCli(), 'install', '--no-save', '--no-audit', '--no-fund', ...tarballs], 540_000, dir),
      'npm install',
    )
    writeFileSync(stampFile, stamp)
  }
}

/** A local .env for a rendered app: development settings on a free port. */
function writeLocalEnv(dir: string, port: number): void {
  const example = readFileSync(join(dir, '.env.example'), 'utf8')
  const local = example
    .replace(/^APP_ENV=.*$/m, 'APP_ENV=local')
    .replace(/^APP_DEBUG=.*$/m, 'APP_DEBUG=true')
    .replace(/^APP_URL=.*$/m, `APP_URL=http://127.0.0.1:${port}`)
    .replace(/^APP_PORT=.*$/m, `APP_PORT=${port}`)
  writeFileSync(join(dir, '.env'), local)
}

/** Start the framework's own server for an app (one process: no orphan on Windows). */
function startServer(
  dir: string,
  port: number,
): { child: ReturnType<typeof spawn>; output: () => string } {
  const bin = join(dir, 'node_modules', '@strutvane', 'framework', 'dist', 'console', 'bin.mjs')
  let output = ''
  const child = spawn(
    process.execPath,
    [bin, 'start', '--port', String(port), '--host', '127.0.0.1'],
    {
      cwd: dir,
      env: childEnv(),
      windowsHide: true,
    },
  )
  child.stdout?.on('data', (chunk: Buffer) => {
    output += chunk.toString()
  })
  child.stderr?.on('data', (chunk: Buffer) => {
    output += chunk.toString()
  })
  return { child, output: () => output }
}

/** Does a `^0.N…` / `^M…` range accept a version (enough semver for this one check)? */
function caretAccepts(range: string, version: string): boolean {
  const want = /^\^(\d+)\.(\d+)\./.exec(range)
  const have = /^(\d+)\.(\d+)\./.exec(version)
  if (want === null || have === null) return false
  return want[1] === have[1] && (want[1] !== '0' || want[2] === have[2])
}

const source = frameworkTarball()
const title =
  'path' in source
    ? 'integration: a rendered app with the real framework'
    : `integration (skipped: ${source.reason})`

// Each step runs real processes (npm, tsc, migrations, a server) on machines of any speed.
describe.skipIf(!('path' in source))(title, { timeout: 300_000 }, () => {
  let port = 0
  let server: ReturnType<typeof spawn> | undefined

  beforeAll(async () => {
    if (!('path' in source)) return
    renderApp(
      APP,
      { name: 'skeleton-it', ui: 'none', auth: 'none', database: 'sqlite', testing: 'vitest' },
      [source.path],
    )
    port = await freePort()
    writeLocalEnv(APP, port)
  }, 600_000)

  afterAll(() => {
    server?.kill()
  })

  it("the installed framework's strutvane.compat accepts its own version (its CLI runs its commands)", () => {
    // 0.2.0-next.0 shipped ^0.1.0-next.0 and refused its own commands; fixed in 0.2.0-next.1.
    const pkg = JSON.parse(
      readFileSync(join(APP, 'node_modules', '@strutvane', 'framework', 'package.json'), 'utf8'),
    ) as { version: string; strutvane: { compat: string } }
    expect(caretAccepts(pkg.strutvane.compat, pkg.version)).toBe(true)
  })

  it('node strut key:generate writes APP_KEY into .env only', () => {
    expectOk(run(['strut.js', 'key:generate']), 'node strut key:generate')
    expect(readFileSync(join(APP, '.env'), 'utf8')).toMatch(/^APP_KEY=\S{40,}$/m)
    expect(readFileSync(join(APP, '.env.example'), 'utf8')).toMatch(/^APP_KEY=$/m)
  })

  it('type-checks (strict) against the real framework types', () => {
    expectOk(
      run([join('node_modules', 'typescript', 'bin', 'tsc'), '--noEmit', '-p', 'tsconfig.json']),
      'tsc',
    )
  })

  it('node strut migrate creates the tables, and the committed .strutvane/ files are current', () => {
    const output = expectOk(run(['strut.js', 'migrate']), 'node strut migrate')
    expect(output).toContain('0001_01_01_000000_create_users_table')
    const stale: string[] = []
    for (const path of GENERATED) {
      const fresh = readFileSync(join(APP, path), 'utf8')
      if (fresh === readFileSync(join(TEMPLATE, path), 'utf8')) continue
      if (process.env['STRUT_UPDATE_GENERATED'] === '1')
        copyFileSync(join(APP, path), join(TEMPLATE, path))
      else stale.push(path)
    }
    expect(stale, 'template/.strutvane is stale: rerun with STRUT_UPDATE_GENERATED=1').toEqual([])
  })

  it('node strut db:seed runs DatabaseSeeder and its UserSeeder', () => {
    const output = expectOk(run(['strut.js', 'db:seed']), 'node strut db:seed')
    expect(output).toContain('UserSeeder')
    const db = new DatabaseSync(join(APP, 'database', 'database.sqlite'), { readOnly: true })
    try {
      const row = db.prepare('SELECT COUNT(*) AS n FROM users').get() as { n: number } | undefined
      expect(row?.n).toBe(5)
      const tables = db
        .prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
        .all()
        .map((table) => String((table as { name: unknown }).name))
      expect(tables).toEqual(expect.arrayContaining(['migrations', 'users']))
    } finally {
      db.close()
    }
  })

  it('SKEL-1: node strut db:seed runs again without a duplicate-email error (firstOrCreate)', () => {
    expectOk(run(['strut.js', 'db:seed']), 'node strut db:seed (second run)')
    const db = new DatabaseSync(join(APP, 'database', 'database.sqlite'), { readOnly: true })
    try {
      const row = db.prepare('SELECT COUNT(*) AS n FROM users').get() as { n: number } | undefined
      expect(row?.n).toBe(5)
    } finally {
      db.close()
    }
  })

  it('node strut migrate:status reports both migrations as ran', () => {
    const output = expectOk(run(['strut.js', 'migrate:status']), 'node strut migrate:status')
    expect(output).not.toContain('pending')
  })

  it("the app's own tests pass (npm test)", () => {
    expectOk(
      run([join('node_modules', 'vitest', 'vitest.mjs'), 'run'], 540_000),
      'vitest in the app',
    )
  }, 560_000)

  it('boots and answers /up, /api/v1/health and /', async () => {
    // The framework's own `start` (what `node strut start` hands over to), as one process, so
    // stopping it never leaves an orphaned server behind on Windows.
    const started = startServer(APP, port)
    server = started.child
    const serverOutput = started.output
    const base = `http://127.0.0.1:${port}`
    try {
      await waitFor(`${base}/up`, 180_000)
    } catch (error) {
      throw new Error(
        `${error instanceof Error ? error.message : String(error)}\n${serverOutput()}`,
      )
    }
    const up = await fetch(`${base}/up`)
    expect(await up.json()).toEqual({ status: 'ok' })
    const health = await fetch(`${base}/api/v1/health`)
    expect(health.status).toBe(200)
    expect(await health.json()).toEqual({ status: 'ok' })
    const home = await fetch(`${base}/`)
    expect(home.status).toBe(200)
    expect(await home.text()).toContain('<h1>skeleton-it</h1>')
    const missing = await fetch(`${base}/api/v1/missing`)
    expect(missing.status).toBe(404)
    expect(up.headers.get('x-content-type-options')).toBe('nosniff')
  }, 240_000)
})

/**
 * Sign-in end to end (demo acceptance AUTH-1, AUTH-2, AUTH-3): an app rendered WITH sign-in, the
 * real framework and the auth package (`STRUT_AUTH_TARBALL`, an `npm pack` of strutvane-auth),
 * booted as a server: the skeleton registers auth's provider, auth accepts the skeleton's class
 * policy, `install:auth` copies the migrations, and `POST /api/v1/auth/sign-in` signs in.
 */
const AUTH_APP = join(WORK, 'it-auth-app')
const authTarball = process.env['STRUT_AUTH_TARBALL']
const authSource: { readonly path: string } | { readonly reason: string } = !('path' in source)
  ? source
  : authTarball === undefined || authTarball === ''
    ? { reason: 'STRUT_AUTH_TARBALL is not set (an npm pack of @strutvane/auth)' }
    : existsSync(authTarball)
      ? { path: authTarball }
      : { reason: `STRUT_AUTH_TARBALL=${authTarball} does not exist` }

describe.skipIf(!('path' in authSource))(
  'path' in authSource
    ? 'integration: sign-in through the API with @strutvane/auth'
    : `integration with sign-in (skipped: ${authSource.reason})`,
  { timeout: 300_000 },
  () => {
    let port = 0
    let server: ReturnType<typeof spawn> | undefined
    // A throwaway password for this run only: never written to a file.
    const password = randomBytes(18).toString('base64url')

    beforeAll(async () => {
      if (!('path' in source) || !('path' in authSource)) return
      renderApp(
        AUTH_APP,
        {
          name: 'skeleton-auth-it',
          ui: 'none',
          auth: 'email',
          database: 'sqlite',
          testing: 'none',
        },
        [source.path, authSource.path],
      )
      port = await freePort()
      writeLocalEnv(AUTH_APP, port)
      expectOk(run(['strut.js', 'key:generate'], 300_000, AUTH_APP), 'node strut key:generate')
    }, 600_000)

    afterAll(() => {
      server?.kill()
    })

    it('type-checks with the provider registered (no cast needed)', () => {
      const providers = readFileSync(join(AUTH_APP, 'bootstrap', 'providers.ts'), 'utf8')
      expect(providers).toContain("import auth from '@strutvane/auth/provider'")
      expectOk(
        run(
          [join('node_modules', 'typescript', 'bin', 'tsc'), '--noEmit', '-p', 'tsconfig.json'],
          300_000,
          AUTH_APP,
        ),
        'tsc',
      )
    })

    it('node strut install:auth sees the provider and copies the migrations; migrate applies them', () => {
      const output = expectOk(run(['strut.js', 'install:auth'], 300_000, AUTH_APP), 'install:auth')
      expect(output).toMatch(/already registered/)
      expectOk(run(['strut.js', 'migrate'], 300_000, AUTH_APP), 'node strut migrate')
      expectOk(run(['strut.js', 'db:seed'], 300_000, AUTH_APP), 'node strut db:seed')
      expectOk(run(['strut.js', 'db:seed'], 300_000, AUTH_APP), 'node strut db:seed (again)')
      expectOk(
        run(
          [
            'strut.js',
            'auth:user:create',
            '--email',
            'admin@example.test',
            '--name',
            'Admin',
            '--password-env',
            'IT_ADMIN_PASSWORD',
          ],
          300_000,
          AUTH_APP,
          { IT_ADMIN_PASSWORD: password },
        ),
        'auth:user:create',
      )
    })

    it('boots with the skeleton policy and signs in at /api/v1/auth/sign-in', async () => {
      const started = startServer(AUTH_APP, port)
      server = started.child
      const base = `http://127.0.0.1:${port}`
      try {
        await waitFor(`${base}/up`, 180_000)
      } catch (error) {
        throw new Error(`${error instanceof Error ? error.message : String(error)}
${started.output()}`)
      }
      const headers = { 'content-type': 'application/json', origin: base }
      const wrong = await fetch(`${base}/api/v1/auth/sign-in`, {
        method: 'POST',
        headers,
        body: JSON.stringify({ email: 'admin@example.test', password: `${password}x` }),
      })
      expect(wrong.status).toBe(401)
      const signIn = await fetch(`${base}/api/v1/auth/sign-in`, {
        method: 'POST',
        headers,
        body: JSON.stringify({ email: 'admin@example.test', password }),
      })
      expect(signIn.status, started.output()).toBe(200)
      const body = (await signIn.json()) as { actor?: { id?: unknown } }
      expect(typeof body.actor?.id).toBe('string')
      const cookie = signIn.headers
        .getSetCookie()
        .map((c) => c.split(';')[0] ?? '')
        .join('; ')
      const me = await fetch(`${base}/api/v1/auth/me`, { headers: { cookie } })
      expect(me.status).toBe(200)
      // The old, unversioned path the UI used before UI-1 is not the auth API.
      const legacy = await fetch(`${base}/api/auth/me`, { headers: { cookie } })
      expect(legacy.status).toBe(404)
    }, 240_000)
  },
)
